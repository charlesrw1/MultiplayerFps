#include "Scripting/LuaSharpDeclarations.h"
#include "Scripting/LuaSharpBinding.h"
#include "Framework/Util.h"
#include <fstream>
#include <iterator>
#include <string>
#include <system_error>

namespace {
namespace fs = std::filesystem;

std::string read_file(const fs::path& path) {
	std::ifstream file(path, std::ios::binary);
	return file ? std::string(std::istreambuf_iterator<char>(file), {}) : std::string();
}

bool write_file(const fs::path& path, const std::string& text) {
	std::error_code ec;
	fs::create_directories(path.parent_path(), ec);
	std::ofstream file(path, std::ios::binary | std::ios::trunc);
	file.write(text.data(), static_cast<std::streamsize>(text.size()));
	if (!file) {
		sys_print(Error, "LuaSharp: cannot write %s\n", path.string().c_str());
		return false;
	}
	sys_print(Info, "LuaSharp: wrote %s\n", path.string().c_str());
	return true;
}
} // namespace

bool write_luasharp_declarations(const fs::path& scripts_dir) {
	ASSERT(!scripts_dir.empty());
	const std::string source = "// Generated by the engine from the reflected classes. Do not edit.\n" + lsbind::declaration_source();
	const fs::path declarations = scripts_dir / ".luasharp" / "engine.ls";
	bool ok = read_file(declarations) == source || write_file(declarations, source);
	const fs::path project = scripts_dir / "luasharp.json";
	if (!fs::exists(project))
		ok = write_file(project, "{\n\t\"declarations\": [\".luasharp\"]\n}\n") && ok;
	return ok;
}
